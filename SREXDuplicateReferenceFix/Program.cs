using System.Globalization;
using System.Text.RegularExpressions;
using Mutagen.Bethesda;
using Mutagen.Bethesda.Plugins;
using Mutagen.Bethesda.Plugins.Cache;
using Mutagen.Bethesda.Plugins.Records;
using Mutagen.Bethesda.Skyrim;
using Mutagen.Bethesda.Synthesis;
using Noggog;

namespace SREXDuplicateReferenceFix;

/// <summary>
/// Finds references that a city-overhaul style plugin transplanted from a city
/// worldspace into a Tamriel cell while leaving the vanilla Tamriel twin of the
/// same base object at the exact same position untouched, and disables the twin
/// using the standard undelete-and-disable pattern (Initially Disabled flag,
/// Enable Parent set to opposite of the Player, Z position -30000).
///
/// Everything is derived from the final load order's winning records on every
/// run, so overrides by other mods (a patch that already disabled the twin, a
/// mod that moved the transplant, ...) are respected automatically. Pairs whose
/// transplanted side is disabled at runtime by a Base Object Swapper transform
/// are skipped, because then the twin is the only visible copy.
/// </summary>
public static class Program
{
    public static Lazy<Settings> _settings = null!;
    public static Settings Settings => _settings.Value;

    private static readonly ModKey SkyrimModKey = ModKey.FromNameAndExtension("Skyrim.esm");
    private static readonly FormKey TamrielFormKey = FormKey.Factory("00003C:Skyrim.esm");

    private const int FlagDeleted = 0x20;
    private const int FlagInitiallyDisabled = 0x800;
    private const float DisabledZ = -30000f;
    private const float DisabledZThreshold = -29000f;

    public static async Task<int> Main(string[] args)
    {
        return await SynthesisPipeline.Instance
            .AddPatch<ISkyrimMod, ISkyrimModGetter>(RunPatch)
            .SetAutogeneratedSettings("Settings", "settings.json", out _settings)
            .SetTypicalOpen(GameRelease.SkyrimSE, "SREX-DuplicateReferenceFix.esp")
            .Run(args);
    }

    private readonly record struct GroupKey(
        FormKey Cell,
        FormKey Base);

    private sealed class Candidate
    {
        public required IModContext<ISkyrimMod, ISkyrimModGetter, IPlacedObject, IPlacedObjectGetter> Context { get; init; }
        public required FormKey Cell { get; init; }
        public required P3Float Position { get; init; }
    }

    // Two references occupy the same spot when their positions agree to
    // within 1 unit on every axis (the criterion the affected references
    // were measured with; rotation is not compared).
    private static bool SameSpot(P3Float a, P3Float b) =>
        Math.Abs(a.X - b.X) < 1f && Math.Abs(a.Y - b.Y) < 1f && Math.Abs(a.Z - b.Z) < 1f;

    public static void RunPatch(IPatcherState<ISkyrimMod, ISkyrimModGetter> state)
    {
        var cache = state.LoadOrder.ToImmutableLinkCache();

        var skipSet = new HashSet<FormKey>();
        foreach (var s in Settings.SkipFormIDs)
        {
            try { skipSet.Add(FormKey.Factory(s.Trim())); }
            catch { Console.WriteLine($"[DupRefFix] Ignoring unparsable Skip FormID entry: {s}"); }
        }

        var transplantFilter = Settings.TransplantFilterPlugins
            .Select(x => x.Trim())
            .Where(x => x.Length > 0)
            .ToHashSet(StringComparer.OrdinalIgnoreCase);

        Console.WriteLine("[DupRefFix] Run started.");
        var bos = new BosSwapReader.Result();
        if (Settings.ReadBosSwapInis)
        {
            try
            {
                bos = BosSwapReader.Read(state.DataFolderPath);
                Console.WriteLine($"[DupRefFix] BOS swap inis: {bos.AbsoluteDisabled.Count} refs disabled outright, {bos.PosRDeltas.Count} refs with relative Z transforms.");
            }
            catch (Exception ex)
            {
                // A BOS read failure must not kill the run: the filter is a
                // safety valve, and pairs it would have caught can still be
                // excluded through the manual skip list.
                Console.WriteLine($"[DupRefFix] BOS swap ini read failed ({ex.GetType().Name}: {ex.Message}); continuing without BOS data.");
            }
        }

        // ---- Pass 1: bucket winning, enabled, Skyrim.esm-born placed objects
        // ---- that sit in Tamriel cells by (cell, base).
        var groups = new Dictionary<GroupKey, List<Candidate>>();
        long scanned = 0;
        foreach (var ctx in state.LoadOrder.PriorityOrder.PlacedObject().WinningContextOverrides(cache))
        {
            var rec = ctx.Record;
            if (rec.FormKey.ModKey != SkyrimModKey) continue;
            if ((rec.MajorRecordFlagsRaw & (FlagDeleted | FlagInitiallyDisabled)) != 0) continue;
            if (rec.Placement == null || rec.Base == null) continue;
            if (!ctx.TryGetParentSimpleContext<IWorldspaceGetter>(out var ws)) continue;
            if (ws.Record.FormKey != TamrielFormKey) continue;
            if (!ctx.TryGetParentSimpleContext<ICellGetter>(out var cell)) continue;

            var key = new GroupKey(
                cell.Record.FormKey,
                rec.Base.FormKey);

            if (!groups.TryGetValue(key, out var list))
            {
                list = new List<Candidate>();
                groups[key] = list;
            }
            list.Add(new Candidate { Context = ctx, Cell = cell.Record.FormKey, Position = rec.Placement.Position });

            if (++scanned % 200000 == 0)
                Console.WriteLine($"[DupRefFix] Scanned {scanned} winning Tamriel placed objects...");
        }
        Console.WriteLine($"[DupRefFix] {scanned} winning Tamriel placed objects grouped by cell and base.");

        // ---- Pass 2: within each (cell, base) bucket, cluster the references
        // ---- that share a spot, classify each cluster, disable native twins.
        int disabled = 0, skipBos = 0, skipFilter = 0, skipManual = 0, skipAmbiguous = 0;
        foreach (var (key, bucket) in groups)
        {
            if (bucket.Count < 2) continue;

            var remaining = new List<Candidate>(bucket);
            while (remaining.Count >= 2)
            {
                var anchor = remaining[0];
                var list = remaining.Where(c => SameSpot(anchor.Position, c.Position)).ToList();
                remaining.RemoveAll(c => list.Contains(c));
                if (list.Count < 2) continue;

            var classified = new List<(Candidate Cand, bool IsNative, bool IsTransplant)>();
            foreach (var cand in list)
            {
                var origin = GetOrigin(state, cand.Context.Record.FormKey);
                if (origin == null)
                {
                    classified.Add((cand, false, false));
                    continue;
                }
                bool isNative = origin.Value.Worldspace == TamrielFormKey && origin.Value.Cell == cand.Cell;
                bool isTransplant = origin.Value.Worldspace != null && origin.Value.Worldspace != TamrielFormKey;
                classified.Add((cand, isNative, isTransplant));
            }

            var natives = classified.Where(c => c.IsNative).ToList();
            var transplants = classified.Where(c => c.IsTransplant).ToList();
            if (natives.Count != 1 || transplants.Count != 1 || classified.Count != 2)
            {
                skipAmbiguous++;
                if (Settings.VerboseLogging)
                    Console.WriteLine($"[DupRefFix] Ambiguous group in cell {key.Cell} base {key.Base}: " +
                        string.Join(", ", classified.Select(c => $"{c.Cand.Context.Record.FormKey} (native={c.IsNative}, transplant={c.IsTransplant})")));
                continue;
            }

            var twin = natives[0].Cand;
            var moved = transplants[0].Cand;
            var twinFk = twin.Context.Record.FormKey;
            var movedFk = moved.Context.Record.FormKey;

            if (skipSet.Contains(twinFk) || skipSet.Contains(movedFk))
            {
                skipManual++;
                Console.WriteLine($"[DupRefFix] Skipped pair (manual skip list): twin {twinFk}, transplant {movedFk}");
                continue;
            }

            if (transplantFilter.Count > 0 && !TouchedByFilterPlugin(state, movedFk, transplantFilter))
            {
                skipFilter++;
                if (Settings.VerboseLogging)
                    Console.WriteLine($"[DupRefFix] Skipped pair (no filter plugin in transplant history; winner is {moved.Context.ModKey}): twin {twinFk}, transplant {movedFk}");
                continue;
            }

            if (bos.IsDisabledAtRuntime(movedFk, moved.Context.Record.Placement!.Position.Z))
            {
                skipBos++;
                Console.WriteLine($"[DupRefFix] Skipped pair (transplant disabled by a BOS transform): twin {twinFk}, transplant {movedFk}");
                continue;
            }

            var placedState = twin.Context.GetOrAddAsOverride(state.PatchMod);
            if (placedState == null)
            {
                Console.WriteLine($"[DupRefFix] WARNING: could not create override for twin {twinFk}");
                continue;
            }

            // Standard undelete-and-disable, matching what SR Exterior Cities
            // itself does to the twins it handles.
            placedState.MajorRecordFlagsRaw |= (int)SkyrimMajorRecord.SkyrimMajorRecordFlag.InitiallyDisabled;
            if (placedState.Placement != null)
            {
                var p = placedState.Placement.Position;
                placedState.Placement.Position = new P3Float(p.X, p.Y, DisabledZ);
            }
            if (placedState.EnableParent != null)
            {
                // Not expected for this class of scenery duplicates, but make
                // the replacement visible instead of silently overwriting a
                // control relationship some other plugin may rely on.
                Console.WriteLine($"[DupRefFix] Note: twin {twinFk} already had an Enable Parent (parent {placedState.EnableParent.Reference.FormKey}); replacing it with opposite-of-Player, per the SR pattern.");
            }
            placedState.EnableParent ??= new EnableParent();
            placedState.EnableParent.Flags = EnableParent.Flag.SetEnableStateToOppositeOfParent;
            placedState.EnableParent.Reference.SetTo(Constants.Player.Cast<IPlacedGetter>());

            disabled++;
            Console.WriteLine($"[DupRefFix] Disabled twin {twinFk} (transplant {movedFk}, cell {key.Cell}, base {key.Base})");
            }
        }

        Console.WriteLine($"[DupRefFix] Done. Disabled {disabled} twins. Skipped: {skipBos} BOS-disabled transplants, {skipFilter} by transplant filter, {skipManual} by manual skip list, {skipAmbiguous} ambiguous clusters.");
    }

    /// <summary>
    /// True when any plugin in the record's override history is in the filter.
    /// The transplant check deliberately looks at the whole history instead of
    /// only the winning override: in the recommended setup a later patch (or
    /// the SR patcher's own output) often wins the transplanted reference,
    /// and the pair is still the transplant a filter plugin performed.
    /// </summary>
    private static bool TouchedByFilterPlugin(IPatcherState<ISkyrimMod, ISkyrimModGetter> state, FormKey formKey, HashSet<string> filter)
    {
        foreach (var ctx in state.LinkCache.ResolveAllContexts<IPlacedObject, IPlacedObjectGetter>(formKey))
        {
            if (filter.Contains(ctx.ModKey.FileName.String)) return true;
        }
        return false;
    }

    /// <summary>
    /// Returns the cell/worldspace the record was born in (its Skyrim.esm version),
    /// or null when no Skyrim.esm version exists. Worldspace is null for interior origins.
    /// </summary>
    private static (FormKey Cell, FormKey? Worldspace)? GetOrigin(IPatcherState<ISkyrimMod, ISkyrimModGetter> state, FormKey formKey)
    {
        foreach (var ctx in state.LinkCache.ResolveAllContexts<IPlacedObject, IPlacedObjectGetter>(formKey))
        {
            if (ctx.ModKey != SkyrimModKey) continue;
            if (!ctx.TryGetParentSimpleContext<ICellGetter>(out var cell)) return null;
            FormKey? ws = null;
            if (ctx.TryGetParentSimpleContext<IWorldspaceGetter>(out var worldspace))
                ws = worldspace.Record.FormKey;
            return (cell.Record.FormKey, ws);
        }
        return null;
    }

    /// <summary>
    /// Reads Base Object Swapper *_SWAP.ini files from the Data folder and collects
    /// the references that a [Transforms] entry disables at runtime: an explicit
    /// Initially Disabled flag, an absolute move below the disable threshold, or a
    /// relative Z move (checked later against the reference's winning Z).
    /// </summary>
    private static class BosSwapReader
    {
        public sealed class Result
        {
            public HashSet<FormKey> AbsoluteDisabled { get; } = new();
            public Dictionary<FormKey, float> PosRDeltas { get; } = new();

            public bool IsDisabledAtRuntime(FormKey fk, float winningZ)
            {
                if (AbsoluteDisabled.Contains(fk)) return true;
                if (PosRDeltas.TryGetValue(fk, out var dz) && winningZ + dz <= DisabledZThreshold) return true;
                return false;
            }
        }

        private static readonly Regex FlagsRegex = new(@"flags\(\s*0x([0-9A-Fa-f]+)\s*\)", RegexOptions.Compiled);
        private static readonly Regex PosARegex = new(@"posA\(\s*[^,]+,[^,]+,\s*(-?[0-9]*\.?[0-9]+)\s*\)", RegexOptions.Compiled);
        private static readonly Regex PosRRegex = new(@"posR\(\s*[^,]+,[^,]+,\s*(-?[0-9]*\.?[0-9]+)\s*\)", RegexOptions.Compiled);

        public static Result Read(string dataFolderPath)
        {
            var result = new Result();
            if (!Directory.Exists(dataFolderPath)) return result;

            foreach (var file in Directory.EnumerateFiles(dataFolderPath, "*_SWAP.ini", SearchOption.TopDirectoryOnly))
            {
                string? section = null;
                foreach (var rawLine in File.ReadLines(file))
                {
                    var line = rawLine.Trim();
                    if (line.Length == 0 || line.StartsWith(';') || line.StartsWith('#')) continue;
                    if (line.StartsWith('['))
                    {
                        section = line;
                        continue;
                    }
                    if (section == null || !section.StartsWith("[Transforms]", StringComparison.OrdinalIgnoreCase)) continue;

                    int pipe = line.IndexOf('|');
                    if (pipe < 0) continue;
                    var lhs = line[..pipe];
                    var props = line[(pipe + 1)..];

                    bool outright = false;
                    foreach (Match m in FlagsRegex.Matches(props))
                    {
                        if (long.TryParse(m.Groups[1].Value, NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var flags)
                            && (flags & FlagInitiallyDisabled) != 0)
                        {
                            outright = true;
                        }
                    }
                    var posA = PosARegex.Match(props);
                    if (posA.Success
                        && float.TryParse(posA.Groups[1].Value, NumberStyles.Float, CultureInfo.InvariantCulture, out var az)
                        && az <= DisabledZThreshold)
                    {
                        outright = true;
                    }

                    if (!TryParseBosFormKey(lhs, out var fk)) continue;

                    if (outright)
                    {
                        result.AbsoluteDisabled.Add(fk);
                        continue;
                    }
                    var posR = PosRRegex.Match(props);
                    if (posR.Success
                        && float.TryParse(posR.Groups[1].Value, NumberStyles.Float, CultureInfo.InvariantCulture, out var dz))
                    {
                        if (!result.PosRDeltas.TryGetValue(fk, out var existing) || dz < existing)
                            result.PosRDeltas[fk] = dz;
                    }
                }
            }
            return result;
        }

        private static bool TryParseBosFormKey(string lhs, out FormKey formKey)
        {
            formKey = default;
            var parts = lhs.Split('~');
            if (parts.Length != 2) return false;
            var idText = parts[0].Trim();
            if (idText.StartsWith("0x", StringComparison.OrdinalIgnoreCase)) idText = idText[2..];
            if (!uint.TryParse(idText, NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var id)) return false;
            try
            {
                var modKey = ModKey.FromNameAndExtension(parts[1].Trim());
                formKey = new FormKey(modKey, id);
                return true;
            }
            catch
            {
                return false;
            }
        }
    }
}
